# Q2. Secure Bank Account
class BankAccount:

  def __init__(self, holder_name: str, initial_balance: float, pin: str):
    self.holder_name = holder_name  # Public attribute
    self.__balance = float(initial_balance)  # Private balance
    self.__pin = str(pin)  # Private PIN

  def deposit(self, amount: float):
    """Rejects zero or negative deposits."""
    if amount > 0:
      self.__balance += amount
      print(
          f"[SUCCESS] Deposited Rs. {amount:.2f}. New Balance:"
          f" Rs. {self.__balance:.2f}"
      )
    else:
      print("[ERROR] Deposit failed: Amount must be greater than zero.")

  def withdraw(self, amount: float, pin: str):
    """Rejects incorrect PINs, non-positive amounts, or insufficient balance."""
    if not self.__verify_pin(pin):
      print("[ERROR] Withdrawal failed: Incorrect PIN.")
      return

    if amount <= 0:
      print("[ERROR] Withdrawal failed: Amount must be greater than zero.")
    elif amount > self.__balance:
      print("[ERROR] Withdrawal failed: Insufficient balance.")
    else:
      self.__balance -= amount
      print(
          f"[SUCCESS] Withdrew Rs. {amount:.2f}. Remaining Balance:"
          f" Rs. {self.__balance:.2f}"
      )

  def get_balance(self, pin: str):
    if self.__verify_pin(pin):
      return self.__balance
    print("[ERROR] Access denied: Incorrect PIN.")
    return None

  def __verify_pin(self, pin: str) -> bool:
    return self.__pin == str(pin)


