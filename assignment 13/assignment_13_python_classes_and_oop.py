# Q1. Student Result Manager
class Student:

  def __init__(self, name: str, marks: int):
    self.name = name  # Public attribute
    self._marks = 0  # Protected attribute
    self.__grade = "F"  # Private attribute
    self.set_marks(marks)

  def set_marks(self, marks: int):
    """Sets marks if valid (0 to 100) and automatically updates the grade."""
    if 0 <= marks <= 100:
      self._marks = marks
      self.__update_grade()
      print(f"[SUCCESS] Marks updated to {self._marks}.")
    else:
      print(
          f"[ERROR] Invalid marks ({marks}). Must be between 0 and 100."
          " Unchanged."
      )

  def get_marks(self) -> int:
    return self._marks

  def get_grade(self) -> str:
    return self.__grade

  def __update_grade(self):
    """Private helper method to assign grade based on marks."""
    if self._marks >= 80:
      self.__grade = "A"
    elif self._marks >= 60:
      self.__grade = "B"
    elif self._marks >= 40:
      self.__grade = "C"
    else:
      self.__grade = "F"

  def display_details(self):
    print(
        f"Student: {self.name} | Marks: {self._marks} | Grade:"
        f" {self.get_grade()}"
    )


