from abc import ABC, abstractmethod


class PaymentMethod(ABC):

  @abstractmethod
  def pay(self, amount: float):
    pass

  @abstractmethod
  def refund(self, amount: float):
    pass


class CardPayment(PaymentMethod):

  def pay(self, amount: float):
    print(f"[CARD PAYMENT] Transaction: DEBIT  | Amount: Rs. {amount:,.2f}")

  def refund(self, amount: float):
    print(f"[CARD PAYMENT] Transaction: REFUND | Amount: Rs. {amount:,.2f}")


class WalletPayment(PaymentMethod):

  def pay(self, amount: float):
    print(f"[WALLET PAYMENT] Transaction: DEBIT  | Amount: Rs. {amount:,.2f}")

  def refund(self, amount: float):
    print(f"[WALLET PAYMENT] Transaction: REFUND | Amount: Rs. {amount:,.2f}")


class BankTransferPayment(PaymentMethod):

  def pay(self, amount: float):
    print(f"[BANK TRANSFER] Transaction: DEBIT  | Amount: Rs. {amount:,.2f}")

  def refund(self, amount: float):
    print(f"[BANK TRANSFER] Transaction: REFUND | Amount: Rs. {amount:,.2f}")


# New payment method added seamlessly without editing process_transaction
class CryptoPayment(PaymentMethod):

  def pay(self, amount: float):
    print(f"[CRYPTO PAYMENT] Transaction: DEBIT  | Amount: Rs. {amount:,.2f}")

  def refund(self, amount: float):
    print(f"[CRYPTO PAYMENT] Transaction: REFUND | Amount: Rs. {amount:,.2f}")


def process_transaction(method: PaymentMethod, amount: float):
  if amount <= 0:
    print("[ERROR] Transaction amount must be positive.")
    return
  method.pay(amount)


