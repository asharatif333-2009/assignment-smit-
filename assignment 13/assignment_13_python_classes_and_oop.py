#Q4. Vehicle Rental System
class Vehicle:

  def __init__(self, brand: str, model: str, daily_rate: float):
    self.brand = brand
    self.model = model
    self.daily_rate = daily_rate

  def calculate_rent(self, days: int) -> float:
    if days <= 0:
      print("[ERROR] Rental duration must be greater than zero days.")
      return 0.0
    return self.daily_rate * days


class Car(Vehicle):

  def calculate_rent(self, days: int) -> float:
    base_rent = super().calculate_rent(days)
    if base_rent == 0.0:
      return 0.0
    insurance_fee = 1000.0
    return base_rent + insurance_fee


class Bike(Vehicle):

  def calculate_rent(self, days: int) -> float:
    base_rent = super().calculate_rent(days)
    if base_rent == 0.0:
      return 0.0
    discount = 0.10 * base_rent
    return base_rent - discount


# --- Demonstration ---
